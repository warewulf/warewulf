func Test_hostsOverlay(t *testing.T) {
	hostname, _ := os.Hostname()
	env := testenv.New(t)
	defer env.RemoveAll()
	env.ImportFile("etc/warewulf/warewulf.conf", "warewulf.conf")
	assert.NoError(t, config.Get().Read(env.GetPath("etc/warewulf/warewulf.conf"), false))
	env.ImportFile("etc/warewulf/nodes.conf", "nodes.conf")
	env.ImportFile("var/lib/warewulf/overlays/hosts/rootfs/etc/hosts.ww", "../rootfs/etc/hosts.ww")

	tests := []struct {
		name string
		args []string
		log  string
		// header marks the start of the generated block; the build host's
		// own /etc/hosts content above it is machine-specific and dropped.
		header string
	}{
		{
			name: "hosts:/etc/hosts",
			args: []string{"--render", "node1", "hosts", "etc/hosts.ww"},
			log:  hosts,
		},
		{
			name:   "hosts:/etc/hosts(server)",
			args:   []string{"--render", hostname, "hosts", "etc/hosts.ww"},
			log:    hosts_server,
			header: "# Do not edit after this line",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cmd := show.GetCommand()
			cmd.SetArgs(tt.args)
			stdout := bytes.NewBufferString("")
			stderr := bytes.NewBufferString("")
			logbuf := bytes.NewBufferString("")
			cmd.SetOut(stdout)
			cmd.SetErr(stderr)
			wwlog.SetLogWriter(logbuf)
			err := cmd.Execute()
			assert.NoError(t, err)
			assert.Empty(t, stdout.String())
			assert.Empty(t, stderr.String())
			log := logbuf.String()
			if tt.header != "" {
				log = skipHeader(log, tt.header)
			}
			assert.Equal(t, strings.ReplaceAll(tt.log, "%HOSTNAME%", hostname), log)
		})
	}
}

// skipHeader keeps the three leading render metadata lines and everything
// from header onward.
func skipHeader(log string, header string) string {
	lines := strings.SplitAfterN(log, "\n", 4)
	meta, body := strings.Join(lines[:3], ""), lines[3]
	return meta + body[strings.Index(body, header):]
}

